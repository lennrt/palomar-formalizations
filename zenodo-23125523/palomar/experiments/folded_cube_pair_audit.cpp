// Second, independently written exhaustive audit for dominating sets of Omega_n
// that contain an isolated selected class. C++17, exact, deterministic.
//
// Differences from folded_cube_anchored.cpp (deliberate, for cross-checking):
//   * Decomposition. Besides the isolated class of the zero word, a dominating
//     set with k-1 further centres must dominate the C(n,2) classes of weight
//     two. A centre with representative weight n/2-2 dominates C(n/2+2,2) of
//     them, a weight-two centre only itself, and no other admissible centre
//     dominates any. The wrapper checks arithmetically that at least three
//     centres of representative weight n/2-2 are forced. This program therefore
//     enumerates rows whose first three weights equal n/2-2.
//   * Enumeration. Column-pattern counts are generated by stars and bars
//     (combinations of separators), not by recursion.
//   * Cover relation. Closed neighbourhoods are built from literal Hamming
//     distances between words with the LOWEST bit fixed to zero as class
//     representatives.
//   * Branching. The LAST uncovered class is branched on, through a generic
//     recursion of arbitrary depth.
//
// Usage: folded_cube_pair_audit n rows depth [threads]
//   rows in {3,4}: number of enumerated centres (the first three of weight n/2-2)
//   depth: number of further centres found by recursion
#include <atomic>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <mutex>
#include <thread>
#include <vector>
using namespace std;
typedef vector<uint64_t> Bits;
static int n, rowsN, depthN, V, W, half;
static vector<uint32_t> rep;            // even words with bit 0 clear
static vector<Bits> hood;               // closed neighbourhoods
static vector<vector<int>> hoodList;
static vector<char> admissible;         // representative weight not in {0, n/2, n}
static int popc(uint32_t x) { int c = 0; while (x) { x &= x - 1; ++c; } return c; }
static int classOf(uint32_t word) {     // binary search among sorted representatives
    if (word & 1u) word ^= ((1u << n) - 1);
    int lo = 0, hi = V - 1;
    while (lo < hi) { int mid = (lo + hi) / 2; if (rep[mid] < word) lo = mid + 1; else hi = mid; }
    return lo;
}
static bool related(uint32_t a, uint32_t b) { int d = popc(a ^ b); return d == 0 || d == half || d == n; }

static bool complete(const Bits& uncovered, int depth, atomic<long long>& nodes) {
    int last = -1;
    for (int q = W - 1; q >= 0 && last < 0; --q)
        if (uncovered[q]) last = q * 64 + 63 - __builtin_clzll(uncovered[q]);
    if (last < 0) return true;
    if (depth == 0) return false;
    if (depth == 1) {
        // one centre must dominate everything: intersect the neighbourhoods
        Bits common = hood[last];
        for (int q = 0; q < W; ++q) {
            uint64_t m = uncovered[q];
            while (m) {
                int x = q * 64 + __builtin_ctzll(m); m &= m - 1;
                bool any = false;
                for (int z = 0; z < W; ++z) { common[z] &= hood[x][z]; any = any || common[z]; }
                if (!any) return false;
            }
        }
        for (int c = 0; c < V; ++c) if ((common[c / 64] >> (c % 64) & 1) && admissible[c]) return true;
        return false;
    }
    Bits next(W);
    for (int c : hoodList[last]) {
        if (!admissible[c]) continue;
        ++nodes;
        for (int q = 0; q < W; ++q) next[q] = uncovered[q] & ~hood[c][q];
        if (complete(next, depth - 1, nodes)) return true;
    }
    return false;
}

int main(int argc, char** argv) {
    if (argc < 4) { fprintf(stderr, "usage: n rows depth [threads]\n"); return 2; }
    n = atoi(argv[1]); rowsN = atoi(argv[2]); depthN = atoi(argv[3]);
    int threads = argc > 4 ? atoi(argv[4]) : 8;
    if (n % 4 || n < 8 || n > 20 || rowsN < 3 || rowsN > 4 || depthN < 0) { fprintf(stderr, "bad parameters\n"); return 2; }
    half = n / 2;
    for (uint32_t x = 0; x < (1u << n); x += 2) if (popc(x) % 2 == 0) rep.push_back(x);
    V = (int)rep.size(); W = (V + 63) / 64;
    hood.assign(V, Bits(W, 0)); hoodList.resize(V); admissible.resize(V);
    for (int i = 0; i < V; ++i) {
        int w = popc(rep[i]);
        admissible[i] = !(w == 0 || w == half || w == n);
        for (int j = 0; j < V; ++j) if (related(rep[i], rep[j])) { hood[i][j / 64] |= 1ull << (j % 64); hoodList[i].push_back(j); }
    }
    // stars and bars over 2^rows patterns
    const int P = 1 << rowsN, bars = P - 1, slots = n + bars;
    vector<int> pos(bars);
    for (int i = 0; i < bars; ++i) pos[i] = i;
    vector<vector<uint32_t>> families;
    unsigned long long tuples = 0;
    const int w0 = half - 2;
    for (;;) {
        ++tuples;
        vector<int> count(P);
        int prev = -1;
        for (int i = 0; i < bars; ++i) { count[i] = pos[i] - prev - 1; prev = pos[i]; }
        count[P - 1] = slots - 1 - prev;
        vector<int> weight(rowsN, 0);
        for (int p = 0; p < P; ++p) for (int r = 0; r < rowsN; ++r) if (p >> r & 1) weight[r] += count[p];
        bool keep = weight[0] == w0 && weight[1] == w0 && weight[2] == w0;
        if (keep && rowsN == 4) keep = weight[3] % 2 == 0 && weight[3] >= 2 && weight[3] <= w0;
        if (keep) {
            vector<uint32_t> words(rowsN, 0);
            int coordinate = 0;
            for (int p = 0; p < P; ++p) for (int j = 0; j < count[p]; ++j, ++coordinate)
                for (int r = 0; r < rowsN; ++r) if (p >> r & 1) words[r] |= 1u << coordinate;
            families.push_back(words);
        }
        int i = bars - 1;
        while (i >= 0 && pos[i] == slots - bars + i) --i;
        if (i < 0) break;
        ++pos[i];
        for (int j = i + 1; j < bars; ++j) pos[j] = pos[j - 1] + 1;
    }
    atomic<size_t> cursor(0); atomic<long long> nodes(0), found(0);
    mutex guard; vector<uint32_t> example;
    auto worker = [&]() {
        for (;;) {
            size_t f = cursor.fetch_add(1);
            if (f >= families.size()) break;
            Bits uncovered(W);
            int zero = classOf(0);
            for (int q = 0; q < W; ++q) {
                uint64_t m = hood[zero][q];
                for (uint32_t w : families[f]) m |= hood[classOf(w)][q];
                uncovered[q] = ~m;
            }
            if (V % 64) uncovered[W - 1] &= (1ull << (V % 64)) - 1;
            if (complete(uncovered, depthN, nodes)) {
                ++found; lock_guard<mutex> lock(guard);
                if (example.empty()) example = families[f];
            }
        }
    };
    vector<thread> pool;
    for (int i = 0; i < threads; ++i) pool.emplace_back(worker);
    for (auto& th : pool) th.join();
    printf("{\"method\":\"pair_cover_stars_bars\",\"n\":%d,\"centres\":%d,\"forced_weight\":%d,"
           "\"pattern_tuples\":%llu,\"row_families\":%zu,\"branch_nodes\":%lld,"
           "\"families_with_completion\":%lld",
           n, 1 + rowsN + depthN, w0, tuples, families.size(), (long long)nodes, (long long)found);
    if (!example.empty()) { printf(",\"example_rows\":["); for (size_t i = 0; i < example.size(); ++i) printf("%s%u", i ? "," : "", example[i]); printf("]"); }
    printf("}\n");
    return 0;
}
